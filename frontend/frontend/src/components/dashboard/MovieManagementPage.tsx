const getAgeRatingOptions = (currentValue?: string | null) => {
  const normalizedValue = currentValue?.trim() ?? "";
  const exists = AGE_RATING_OPTIONS.some((option) => option.value === normalizedValue);
  if (!normalizedValue || exists) return AGE_RATING_OPTIONS;

  return [
    ...AGE_RATING_OPTIONS,
    { value: normalizedValue, label: `${normalizedValue} - Theo dữ liệu TMDB` },
  ];
};

const mapFormat = (f: string) => {
  const normalized = String(f ?? "").toUpperCase();
  if (normalized === "STANDARD"
    || normalized === "2D" || normalized === "3D"
    || normalized === "_2D" || normalized === "_3D"
    || normalized === "SCREENX") return "STANDARD";
  if (normalized === "4DX") return "_4DX";
  if (normalized === "DOLBY") return "STANDARD";
  return normalized;
};

const normalizeProjectionType = (value?: string | null) => {
  const normalized = String(value ?? "").toUpperCase();
  if (normalized === "3D" || normalized === "THREE_D") return "THREE_D";
  if (normalized === "2D" || normalized === "TWO_D") return "TWO_D";
  return normalized;
};

const getAllowedProjectionOptions = (
  format: string | null | undefined,
  options: MoviePresentationOptionsResponse,
) => mapFormat(String(format ?? "")) === "STANDARD"
  ? options.projectionTypes
  : options.projectionTypes.filter((option) => normalizeProjectionType(option.value) === "THREE_D");

const normalizeLanguageType = (value?: string | null) => {
  const normalized = String(value ?? "").toUpperCase();
  if (normalized === "DUBBED" || normalized.includes("LỒNG") || normalized.includes("LONG")) return "DUBBED";
  if (normalized === "ORIGINAL" || normalized.includes("NGUYÊN") || normalized.includes("GOC") || normalized.includes("GỐC")) return "ORIGINAL";
  if (normalized === "SUBTITLE" || normalized.includes("PHỤ") || normalized.includes("PHU")) return "SUBTITLE";
  return normalized;
};

const formatPresentationLabel = (presentation?: MoviePresentationRequest | null) => {
  const displayName = (presentation as (MoviePresentationRequest & { displayName?: string | null }) | null)?.displayName?.trim();
  return formatPresentationLabelFromFields({
    ...(presentation ?? {}),
    presentationName: displayName || presentation?.label,
  }) || "Phiên bản chiếu";
};

const getMoviePresentationLabels = (movie: MovieResponse) => {
  return (movie.presentations ?? [])
    .filter((presentation) => presentation.active !== false)
    .sort((a, b) => (a.sortOrder ?? 0) - (b.sortOrder ?? 0))
    .map(formatPresentationLabel)
    .filter(Boolean);
};

const getOptionLabel = (
  options: MoviePresentationOptionsResponse["formats"],
  value?: string | null,
) => options.find((option) => option.value === value)?.label || value || "";

const formatPresentationLabelFromOptions = (
  presentation: MoviePresentationRequest,
  options: MoviePresentationOptionsResponse,
) => {
  if (presentation.label?.trim()) {
    return formatPresentationLabelFromFields({
      ...presentation,
      presentationName: presentation.label.trim(),
    });
  }
  return [
    getOptionLabel(options.formats, mapFormat(String(presentation.format ?? ""))),
    getOptionLabel(options.projectionTypes, normalizeProjectionType(presentation.projectionType)),
    getOptionLabel(options.languageTypes, normalizeLanguageType(presentation.languageType)),
  ].filter(Boolean).join(" - ") || "Chưa cấu hình";
};

const createPresentationFromOptions = (
  options: MoviePresentationOptionsResponse,
  sortOrder: number,
): MoviePresentationRequest | null => {
  const format = options.formats[0]?.value;
  const projectionType = options.projectionTypes[0]?.value;
  const languageType = options.languageTypes[0]?.value;
  if (!format || !projectionType || !languageType) return null;

  return {
    format,
    projectionType,
    languageType,
    audioLanguage: "",
    subtitleLanguage: "",
    active: true,
    sortOrder,
  };
};

const getMovieGenreLabels = (movie: MovieResponse) => {
  const labels = [
    ...(movie.genres ?? []).map((genre) => genre.name),
    ...(movie.types ?? []),
  ].filter(Boolean);
  return Array.from(new Set(labels));
};

const formatMovieDate = (value?: string | null) => value ? value.split("-").reverse().join("/") : "—";

const comparablePresentations = (presentations?: MoviePresentationRequest[] | null) =>
  (presentations ?? [])
    .filter((presentation) => presentation.active !== false)
    .map((presentation) => ({
      presentationId: presentation.presentationId ?? null,
      format: mapFormat(String(presentation.format ?? "")),
      projectionType: normalizeProjectionType(presentation.projectionType),
      languageType: normalizeLanguageType(presentation.languageType),
      audioLanguage: presentation.audioLanguage || "",
      subtitleLanguage: presentation.subtitleLanguage || "",
      label: presentation.label || "",
      active: presentation.active !== false,
    }))
    .sort((a, b) => {
      const idCompare = String(a.presentationId ?? "").localeCompare(String(b.presentationId ?? ""));
      if (idCompare !== 0) return idCompare;
      return `${a.format}-${a.projectionType}-${a.languageType}-${a.label}`
        .localeCompare(`${b.format}-${b.projectionType}-${b.languageType}-${b.label}`);
    });

const buildMoviePayload = <T extends MovieCreateRequest | MovieUpdateRequest>(source: T): T => {
  const presentations = (source.presentations ?? [])
    .map((presentation, index) => ({
      ...presentation,
      format: mapFormat(String(presentation.format ?? "")),
      projectionType: mapFormat(String(presentation.format ?? "")) === "STANDARD"
        ? normalizeProjectionType(presentation.projectionType)
        : "THREE_D",
      languageType: normalizeLanguageType(presentation.languageType),
      active: presentation.active !== false,
      sortOrder: index,
      label: isAutoGeneratedPresentationLabel(presentation.label) ? null : presentation.label,
    }));
  const formatsFromPresentations = Array.from(new Set(
    presentations
      .filter((presentation) => presentation.active !== false)
      .map((presentation) => mapFormat(String(presentation.format ?? "")))
      .filter(Boolean)
  ));
  return {
    ...source,
    formats: formatsFromPresentations,
    presentations,
  };
};

